async (page) => {
  const assert=(ok,message)=>{if(!ok)throw Error(message);};
  const data=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('oneflow-demo-v1')));
  const click=async(name)=>{await page.getByRole('button',{name,exact:true}).click();await page.locator('main').ariaSnapshot();};
  const send=async(text)=>{await page.getByRole('textbox',{name:'告诉 OneFlow 你的需求'}).fill(text);await click('发送');};
  const waitFor=async(fn)=>{await page.waitForFunction(fn);};
  await click('首页');
  await page.getByRole('button',{name:/02 家，比你先准备好/}).click();
  await page.locator('main').ariaSnapshot();
  await click('开始规划');
  await page.getByRole('slider',{name:'目标温度',exact:true}).focus();
  await page.keyboard.press('Home');
  for(let i=0;i<8;i++)await page.keyboard.press('ArrowRight');
  let s=await data();assert(s.tasks[0].config.temp===24,'GUI temperature not updated');
  await send('空调改成25度');s=await data();assert(s.tasks[0].config.temp===25,'LUI did not update same plan');
  const id=s.tasks[0].id;
  await send('不要辣的，换成有汤的');s=await data();assert(s.tasks[0].id===id&&s.tasks[0].config.dinner===1&&s.tasks[0].config.temp===25,'Dinner lost context');
  await click('查看归家计划');await click('确认归家计划');
  await page.waitForFunction(()=>JSON.parse(localStorage.getItem('oneflow-demo-v1')).tasks[0].steps.filter(s=>s.status==='completed').length>=2);
  await page.getByRole('button',{name:/40℃ 智能热水器/}).click();
  await page.getByRole('checkbox',{name:'设备在线状态',exact:true}).uncheck();await click('关闭');
  await click('推进模拟时间');
  await page.getByText('智能热水器连接失败，设备当前离线',{exact:true}).waitFor();
  s=await data();assert(s.tasks[0].clock===1095,'Expected 18:15');
  await click('推进模拟时间');
  await page.waitForFunction(()=>JSON.parse(localStorage.getItem('oneflow-demo-v1')).tasks[0].steps.some(s=>s.targetDeviceId==='ac'&&s.status==='completed'));
  s=await data();assert(s.devices.find(d=>d.id==='ac').properties.temperature===25,'Scheduled AC not applied');
  await send('空调改成24度');
  s=await data();assert(s.devices.find(d=>d.id==='ac').properties.temperature===25,'Executed AC change skipped confirmation');
  await click('确认新计划');
  await page.waitForFunction(()=>JSON.parse(localStorage.getItem('oneflow-demo-v1')).devices.find(d=>d.id==='ac').properties.temperature===24);
  await send('我堵车了，预计晚20分钟到家');
  s=await data();assert(s.tasks[0].config.eta===1120,'ETA changed before confirmation');
  await click('确认新计划');
  s=await data();assert(s.tasks[0].config.eta===1140,'ETA not delayed');
  assert(s.tasks[0].steps.find(s=>s.targetDeviceId==='light').scheduledTime===1135,'Pending lights not rescheduled');
  assert(s.devices.find(d=>d.id==='ac').properties.temperature===24,'Completed device reverted');
  await click('暂停未执行步骤');s=await data();assert(s.tasks[0].status==='paused','Pause failed');
  await click('恢复执行');await click('推进模拟时间');
  await page.waitForFunction(()=>JSON.parse(localStorage.getItem('oneflow-demo-v1')).tasks[0].steps.some(s=>s.targetDeviceId==='light'&&s.status==='completed'));
  await click('推进模拟时间');s=await data();assert(s.tasks[0].status==='partial_failed','Offline task must be partial failure');
  await page.screenshot({path:'output/playwright/home-partial-failure.png',fullPage:true});
  await page.getByRole('button',{name:'查看设备',exact:true}).first().click();await page.getByRole('checkbox',{name:'设备在线状态',exact:true}).check();await click('关闭');
  await click('重试');
  await page.waitForFunction(()=>JSON.parse(localStorage.getItem('oneflow-demo-v1')).tasks[0].status==='completed');
  s=await data();assert(s.devices.find(d=>d.id==='water').properties.temperature===45,'Retry did not preheat');
  assert(s.tasks[0].steps.filter(s=>s.targetDeviceId==='ac'&&s.status==='completed').length===2,'AC history not preserved');
  const saved=JSON.stringify(s);await page.reload();await page.getByRole('heading',{name:/晚上好|下午好|早上好/}).waitFor();
  assert(JSON.stringify(await data())===saved,'Refresh did not restore persisted state');
  return 'PASS home: GUI + LUI, scheduled execution, offline isolation, confirmation after execution, ETA rescheduling, pause/resume, retry, preserved history, refresh';
}
