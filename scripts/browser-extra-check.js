async(page)=>{
  const assert=(v,m)=>{if(!v)throw Error(m);};
  const data=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('oneflow-demo-v1')));
  const click=async(name)=>{await page.getByRole('button',{name,exact:true}).click();await page.locator('main').ariaSnapshot();};
  await page.locator('main').ariaSnapshot();
  await click('服务');
  await page.getByRole('button',{name:/影音娱乐 Agent/}).click();
  await click('断开连接');await click('关闭');
  await click('首页');await page.getByRole('button',{name:/01 把客厅/}).click();await click('开始规划');
  await page.getByRole('button',{name:'选择这部',exact:true}).nth(1).click();await click('暂不购买');await click('下一步');await click('确认开启观影模式');
  await click('确认执行');
  await page.getByRole('heading',{name:'先连接服务，再继续',exact:true}).waitFor();
  let s=await data();assert(s.tasks[0].status==='pending_confirmation','Unconnected service executed');
  await click('同意授权并连接');await click('确认执行');
  await page.getByRole('heading',{name:'科幻电影之夜准备完成！',exact:true}).waitFor();
  await click('查看电视');await page.getByRole('button',{name:'开始播放',exact:true}).click();await click('关闭');
  await page.screenshot({path:'output/playwright/mobile-movie.png',fullPage:true});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Chat overflow on mobile');
  await click('首页');await page.getByRole('button',{name:/03 去收集一点新风景/}).click();await click('开始规划');
  await page.getByLabel('预算（元）').fill('1800');
  await page.getByLabel('酒店推荐').selectOption('1');
  await page.getByLabel('两日路线').selectOption('1');
  await click('确认行程并添加至日历');await click('确认执行');
  await page.getByRole('heading',{name:'周末轻旅行准备完成！',exact:true}).waitFor();
  s=await data();assert(s.tasks[0].config.budget===1800&&s.tasks[0].config.hotel===1,'Travel edits lost');assert(s.devices.find(d=>d.id==='car').properties.destination==='杭州','Car navigation missing');
  assert(s.tasks[0].steps.some(s=>s.title==='添加至日历'&&s.status==='completed'),'Calendar missing');
  await click('首页');await page.getByRole('button',{name:/04 灵感/}).click();await click('开始规划');
  await page.getByLabel('继续处理的提醒时间').fill('20:30');await click('查看接续计划');await click('确认执行');
  await page.getByRole('heading',{name:'跨端接续办公准备完成！',exact:true}).waitFor();
  await click('查看设备');await click('打开文档与待办');
  assert(await page.getByText('完善用户旅程与核心场景',{exact:true}).isVisible(),'Document context missing');await click('关闭');
  await page.getByRole('textbox',{name:'告诉 OneFlow 你的需求'}).fill('提醒改成21:00');await click('发送');await click('确认新计划');
  await page.waitForFunction(()=>JSON.parse(localStorage.getItem('oneflow-demo-v1')).tasks[0].status==='completed');
  s=await data();assert(s.tasks[0].config.reminder==='21:00','Reminder edit failed');
  await page.setViewportSize({width:1440,height:1080});await page.evaluate(()=>window.scrollTo(0,0));await page.screenshot({path:'output/playwright/work-completed.png',fullPage:true});
  await click('首页');await page.evaluate(()=>window.scrollTo(0,0));await page.screenshot({path:'output/playwright/desktop-home.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});await page.evaluate(()=>window.scrollTo(0,0));await page.screenshot({path:'output/playwright/mobile-home.png',fullPage:true});
  return 'PASS: mobile movie flow + preview, service authorization gate, travel editing and car/calendar, document context, reminder update, responsive layout';
}
